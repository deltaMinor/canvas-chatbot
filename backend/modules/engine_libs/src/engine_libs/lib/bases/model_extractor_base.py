    @raise_exception(
        "Failed to extract attribute info.",
        exception_logger=logger,
    )
    def _extract_attribute_info(
        self, answer: Any, param_key: str, parameters: dict[str, Any]
    ) -> dict[str, Any]:
        """
        Extract attribute information from answer.

        Args:
            answer: The answer data
            param_key: The parameter key
            parameters: The parameters configuration

        Returns:
            Dictionary with extracted attribute
        """
        new_object = {}
        new_attribute_name = parameters["parameters"][0]
        new_object[new_attribute_name] = self.get_answer_from_structure(
            DataExtractorUtil.get_value_from_structure_recursive(answer, param_key)
        )
        return new_object

    @raise_exception(
        "Failed to extract object ref info.",
        exception_logger=logger,
    )
    def _extract_object_ref_info(
        self, answer: Any, param_key: str, parameters: dict[str, Any]
    ) -> dict[str, Any]:
        """
        Extract object reference information from answer.

        Args:
            answer: The answer data
            param_key: The parameter key
            parameters: The parameters configuration

        Returns:
            Dictionary with extracted object reference
        """
        new_object = {}
        answer_key = DataExtractorUtil.get_value_from_structure_recursive(
            answer, param_key
        )

        if answer_key is not None:
            if isinstance(answer_key, list):
                new_object_ref = []
                for ref_obj in answer_key:
                    new_o = self.create_new_object_ref(
                        self.get_answer_from_structure(ref_obj),
                        parameters["parameters"],
                    )
                    new_object_ref.append(new_o)
            else:
                new_object_ref = self.create_new_object_ref(
                    self.get_answer_from_structure(answer_key),
                    parameters["parameters"],
                )

            new_obj_attribute_name = parameters["parameters"]["new_attribute_name"]
            new_object[new_obj_attribute_name] = new_object_ref

        return new_object

    @raise_exception(
        "Failed to extract key value mapping.",
        exception_logger=logger,
    )
    def _extract_key_value_mapping(
        self,
        answer: Any,
        param_key: str,
        parameters: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Extract key-value mapping from answer.

        Args:
            answer: The answer data
            param_key: The parameter key
            parameters: The parameters configuration

        Returns:
            Dictionary with extracted key-value mapping
        """
        new_object = {}
        answer_key = DataExtractorUtil.get_value_from_structure_recursive(
            answer, param_key
        )
        _key = parameters["parameters"]["new_attribute_name"]
        attribute_key_to_fetch = parameters["parameters"]["attribute_key_to_fetch"]

        if not answer_key or not attribute_key_to_fetch:
            new_object[_key] = ""
        else:
            _value = answer_key[attribute_key_to_fetch]
            new_object[_key] = _value

        return new_object

    @raise_exception(
        "Failed to extract object id.",
        exception_logger=logger,
    )
    def _extract_object_id(
        self,
        answer: Any,
        param_key: str,
    ) -> dict[str, Any]:
        """
        Extract object ID from answer.

        Args:
            answer: The answer data
            param_key: The parameter key

        Returns:
            Dictionary with extracted object ID
        """
        new_object = {}
        new_object["id"] = answer[param_key]
        return new_object

    # ============================================================================
    # DYNAMIC KEY HANDLING METHODS
    # ============================================================================

    @raise_exception(
        "Failed to process answer with dynamic keys.",
        exception_logger=logger,
    )
    def _process_answer_with_dynamic_keys(
        self,
        answer: Any,
        parameters: list[list[dict[str, Any]]],
        dynamic_keynames: list[str],
        return_object: list[dict[str, Any]],
        obj_id: int,
    ) -> int:
        """Process a single answer with dynamic key handling."""
        for grouping_for_new_object in parameters:
            new_list_groupings = self._process_parameter_grouping(
                grouping_for_new_object, dynamic_keynames
            )

            for grouping in new_list_groupings:
                new_object = self._create_object_from_grouping(answer, grouping, obj_id)
                return_object.append(new_object)
                obj_id += 1

        return obj_id

    # ============================================================================
    # OBJECT CREATION METHODS
    # ============================================================================

    @raise_exception(
        "Failed to create object from grouping.",
        exception_logger=logger,
    )
    def _create_object_from_grouping(
        self,
        answer: Any,
        grouping: list[dict[str, Any]],
        obj_id: int,
    ) -> dict[str, Any]:
        """Create a single object from a parameter grouping."""
        new_object = {"id": obj_id}

        for param in grouping:
            mini_object = self.extract_cell_info(answer, param)
            new_object.update(mini_object)

        return new_object

    @raise_exception(
        "Failed to find dynamic keynames.",
        exception_logger=logger,
    )
    def _find_dynamic_keynames(
        self,
        answer: Any,
        key_pattern: re.Pattern,
    ) -> list[str]:
        """
        Find dynamic key names in the answer.

        Args:
            answer: The answer data to search
            key_pattern: The regex pattern for dynamic keys

        Returns:
            List of dynamic key names
        """
        dynamic_keynames = []
        keynames = set(answer.keys())
        for keyname in keynames:
            if bool(key_pattern.fullmatch(keyname)):
                dynamic_keynames.append(keyname)
        return dynamic_keynames

    @raise_exception(
        "Failed to process parameter grouping.",
        exception_logger=logger,
    )
    def _process_parameter_grouping(
        self,
        grouping_for_new_object: list[dict[str, Any]],
        dynamic_keynames: list[str],
    ) -> list[list[dict[str, Any]]]:
        """
        Process parameter grouping with dynamic key handling.

        Args:
            grouping_for_new_object: The parameter grouping to process
            dynamic_keynames: List of dynamic key names

        Returns:
            List of processed parameter groupings
        """
        dict_new_params = {}
        dict_static_params = {}

        for param in grouping_for_new_object:
            if "DYNAMIC" in param["keyName"]:
                self._process_dynamic_params(param, dynamic_keynames, dict_new_params)
            else:
                dict_static_params[param["keyName"]] = param

        if len(dict_new_params) > 0:
            return self._combine_dynamic_and_static_params(
                dict_new_params, dict_static_params
            )
        else:
            return grouping_for_new_object

    @raise_exception(
        "Failed to process dynamic params.",
        exception_logger=logger,
    )
    def _process_dynamic_params(
        self,
        param: dict[str, Any],
        dynamic_keynames: list[str],
        dict_new_params: dict[str, list[dict[str, Any]]],
    ) -> None:
        """
        Process dynamic parameters by creating copies for each dynamic key.

        Args:
            param: The parameter to process
            dynamic_keynames: List of dynamic key names
            dict_new_params: Dictionary to store new parameters
        """
        for keyname in dynamic_keynames:
            if keyname not in dict_new_params:
                dict_new_params[keyname] = []
            new_param = copy.deepcopy(param)
            new_param["keyName"] = param["keyName"].replace("DYNAMIC", keyname)
            dict_new_params[keyname].append(new_param)

    @raise_exception(
        "Failed to combine dynamic and static params.",
        exception_logger=logger,
    )
    def _combine_dynamic_and_static_params(
        self,
        dict_new_params: dict[str, list[dict[str, Any]]],
        dict_static_params: dict[str, dict[str, Any]],
    ) -> list[list[dict[str, Any]]]:
        """
        Combine dynamic and static parameters.

        Args:
            dict_new_params: Dictionary of new parameters
            dict_static_params: Dictionary of static parameters

        Returns:
            List of combined parameter groupings
        """
        # Remove static key names from dynamic params
        for static_keyname in dict_static_params.keys():
            dict_new_params.pop(static_keyname, None)

        # Add static parameters to each dynamic grouping
        new_list_groupings = dict_new_params.values()
        for group in new_list_groupings:
            group.extend(list(dict_static_params.values()))

        return new_list_groupings
